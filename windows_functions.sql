#windows function  
#Windows functions are the functions that used to perform calculation on the set of rows related to the current row
#Three parts
#1 over = used to apply a function over a wondow

# Difference (GROUP BY vs. Window Functions):
#GROUP BY collapses your rows. It squashes multiple 
#rows into a single row. 

#Window Functions keep all your rows and the calculated result is added as
#a new column alongside the original details.

#and problem is we cannot use non aggregated column with aggrated column
#in group by thats why we use windows function

use world;
select code ,name,continent,population,sum(population) over() , avg(population) over() from country;

#partition by= it is same as group by  which divide your data in groups
select code ,name,continent,population,sum(population) over(partition by continent) from country;

#what is the running sum or cummalative sum
select code ,name,continent,population,sum(population) over(order by population) from country;


select code ,name,continent,region, population,sum(population) over(partition by continent) ,
sum(population) over(partition by continent,region)
from country;

