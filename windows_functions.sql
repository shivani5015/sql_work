#1. ROW_NUMBER()
#What it does: Assigns a strict, sequential integer (1, 2, 3, 4...) to every row. No ties allowed.

select * , row_number() over() from  employees;
#partion by dep
select * , row_number() over(partition by department) from  employees;
#according to date
select * , row_number() over(partition by department order by hire_date) from  employees;

#2. RANK()
#What it does: Assigns a rank based on the specified order.
# If two or more rows share identical values, they receive the same rank and it skip values.

select *, rank() over(order by salary) from employees;

#3. DENSE_RANK()
#What it does: Assigns a rank based on the specified order, similar to RANK().but dont skip values

select *,dense_rank() over(partition by department order by salary) from employees;


















































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































  
